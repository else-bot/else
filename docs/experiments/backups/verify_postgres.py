#!/usr/bin/env python3
"""Disposable PostgreSQL -> age -> PostgreSQL check using only synthetic data."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile
import time
import uuid

IMAGE = "postgres@sha256:5c4783a8cc3f0074912164f94dfa1be4e043438f0f707cf968d7af9a0d31a2c8"
SCHEMA = """
CREATE TABLE bots (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL);
CREATE TABLE messages (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bot_id bigint NOT NULL REFERENCES bots(id), body text NOT NULL, metadata jsonb NOT NULL);
CREATE TABLE settings (name text PRIMARY KEY, value text NOT NULL);
"""
ROWS = """
INSERT INTO bots(name) VALUES ('synthetic alpha'), ('synthetic beta');
INSERT INTO messages(bot_id, body, metadata)
SELECT 1 + n % 2, 'synthetic message ' || n || ' café 日本語', jsonb_build_object('sequence', n)
FROM generate_series(1, 37) AS n;
INSERT INTO settings VALUES ('owner-marker', 'source-state');
"""
CANONICAL = """
SELECT jsonb_build_object(
 'bots', (SELECT jsonb_agg(to_jsonb(b) ORDER BY id) FROM bots b),
 'messages', (SELECT jsonb_agg(to_jsonb(m) ORDER BY id) FROM messages m),
 'settings', (SELECT jsonb_agg(to_jsonb(s) ORDER BY name) FROM settings s),
 'bot_sequence', (SELECT jsonb_build_array(last_value, is_called) FROM bots_id_seq),
 'message_sequence', (SELECT jsonb_build_array(last_value, is_called) FROM messages_id_seq)
)::text;
"""


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--binary", required=True, type=Path)
    parser.add_argument("--results", required=True, type=Path)
    args = parser.parse_args()
    os.umask(0o077)
    scratch = Path("/tmp/elsebot-research-backups")
    scratch.mkdir(exist_ok=True)
    name = "elsebot-research-backups-" + uuid.uuid4().hex[:16]
    checks = []

    def docker(*arguments, input=None, check=True, stdout=subprocess.PIPE):
        return subprocess.run(["docker", *arguments], input=input, stdout=stdout,
                              stderr=subprocess.PIPE, check=check, timeout=60)

    def sql(database, statement, check=True):
        return docker("exec", "-i", name, "psql", "-X", "-U", "postgres", "-d", database,
                      "--set", "ON_ERROR_STOP=1", "--tuples-only", "--no-align",
                      input=statement.encode(), check=check)

    created = False
    result = None
    with tempfile.TemporaryDirectory(prefix="postgres-", dir=scratch) as directory:
        root = Path(directory)
        try:
            docker("create", "--name", name, "--network", "none", "--memory", "384m", "--cpus", "1",
                   "--pids-limit", "128", "--tmpfs", "/var/lib/postgresql:rw,size=192m",
                   "--shm-size", "16m", "-e", "POSTGRES_HOST_AUTH_METHOD=trust", IMAGE,
                   "postgres", "-c", "shared_buffers=32MB", "-c", "max_connections=10",
                   "-c", "wal_level=minimal", "-c", "max_wal_senders=0")
            created = True
            docker("start", name)
            for _ in range(120):
                process = docker("exec", name, "cat", "/proc/1/comm", check=False)
                if process.stdout.strip() == b"postgres" and docker("exec", name, "pg_isready", "-U", "postgres", check=False).returncode == 0:
                    break
                time.sleep(0.25)
            else:
                raise RuntimeError("synthetic PostgreSQL did not become ready")
            inspected = json.loads(docker("inspect", name).stdout)[0]
            assert inspected["HostConfig"]["NetworkMode"] == "none"
            assert not inspected["HostConfig"].get("PortBindings")
            assert not any(mount["Type"] in ("volume", "bind") for mount in inspected["Mounts"])
            checks.append("unique isolated container, no network, no published ports, tmpfs data only")
            for database in ("synthetic_source", "synthetic_restored", "synthetic_existing"):
                docker("exec", name, "createdb", "-U", "postgres", "--template=template0", database)
            sql("synthetic_source", SCHEMA + ROWS)
            source_rows = sql("synthetic_source", CANONICAL).stdout
            archive = root / "database.dump"
            with archive.open("wb") as output:
                docker("exec", name, "pg_dump", "-U", "postgres", "--format=custom",
                       "--no-owner", "--no-acl", "synthetic_source", stdout=output)
            assert archive.read_bytes()[:5] == b"PGDMP"
            checks.append("real pg_dump custom archive produced from two bots and 37 messages")
            master, salt = root / "synthetic-master", root / "salt"
            master.write_bytes(os.urandom(32))
            salt.write_bytes(os.urandom(32))

            def crypto(mode, source, target):
                subprocess.run([str(args.binary.resolve()), mode, str(master), str(salt), str(source), str(target)],
                               check=True, capture_output=True, timeout=60)

            encrypted, decrypted = root / "database.dump.age", root / "verified.dump"
            crypto("encrypt", archive, encrypted)
            crypto("decrypt", encrypted, decrypted)
            digest = hashlib.sha256(archive.read_bytes()).hexdigest()
            assert hashlib.sha256(decrypted.read_bytes()).hexdigest() == digest
            checks.append("real custom dump encrypted and fully decrypted by current age fixture, exact SHA-256")
            with decrypted.open("rb") as stream:
                listing = docker("exec", "-i", name, "pg_restore", "--list", input=stream.read()).stdout
            assert b"TABLE DATA public messages" in listing

            def restore(database, check=True):
                return docker("exec", "-i", name, "pg_restore", "-U", "postgres", "--single-transaction",
                              "--exit-on-error", "--no-owner", "--no-acl", "--dbname=" + database,
                              input=decrypted.read_bytes(), check=check)

            restore("synthetic_restored")
            restored_rows = sql("synthetic_restored", CANONICAL).stdout
            assert restored_rows == source_rows
            checks.append("pg_restore into fresh template0 database preserves all rows, Unicode, JSON, and sequence state")
            invalid = sql("synthetic_restored", "INSERT INTO messages(bot_id,body,metadata) VALUES (999,'invalid','{}');", check=False)
            assert invalid.returncode != 0 and b"foreign key constraint" in invalid.stderr
            assert sql("synthetic_restored", "SELECT count(*) FROM messages;").stdout.strip() == b"37"
            checks.append("restored foreign key rejects invalid bot reference, original 37 messages remain")
            sql("synthetic_existing", SCHEMA + ROWS + "UPDATE settings SET value='preserve-existing-owner-state';")
            before = sql("synthetic_existing", CANONICAL).stdout
            failed = restore("synthetic_existing", check=False)
            assert failed.returncode != 0 and b"already exists" in failed.stderr
            assert sql("synthetic_existing", CANONICAL).stdout == before
            checks.append("single-transaction restore over existing schema fails and preserves all existing rows and sequences")
            result = {"status": "PASS", "date": "2026-11-02", "synthetic_only": True,
                      "image": IMAGE, "container_name": name,
                      "encryption_library": "age 0.12.1", "format": "age-encryption.org/v1",
                      "postgres_version": docker("exec", name, "postgres", "--version").stdout.decode().strip(),
                      "pg_dump_version": docker("exec", name, "pg_dump", "--version").stdout.decode().strip(),
                      "pg_restore_version": docker("exec", name, "pg_restore", "--version").stdout.decode().strip(),
                      "archive_bytes": archive.stat().st_size, "encrypted_bytes": encrypted.stat().st_size,
                      "archive_sha256": digest, "canonical_source_rows_sha256": hashlib.sha256(source_rows).hexdigest(),
                      "canonical_restored_rows_sha256": hashlib.sha256(restored_rows).hexdigest(),
                      "row_counts": {"bots": 2, "messages": 37, "settings": 1},
                      "existing_destination_restore_exit": failed.returncode,
                      "existing_destination_unchanged": True, "checks": checks, "check_count": len(checks),
                      "remote_upload": "not attempted", "full_application_restore": "UNVERIFIED"}
        finally:
            if created:
                docker("rm", "--force", "--volumes", name)
                assert docker("container", "inspect", name, check=False).returncode != 0
        result["cleanup"] = "own container removed and absence verified; tmpfs data discarded; no volumes or bind mounts created"
        args.results.write_text(json.dumps(result, indent=2) + "\n")
        print(json.dumps({"status": "PASS", "checks": len(checks), "results": str(args.results), "cleanup": "verified"}))


if __name__ == "__main__":
    main()
